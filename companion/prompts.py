def format_numbered_batch(batch: Optional[List[Dict[str, Any]]]) -> str:
    """本轮聚合批次 → 提示词里的编号块；不满足条件时返回空串（调用方走老路径）。

    为什么只有 ≥2 条才编号：他发一条时"引用哪句"这个问题根本不存在，
    无条件塞个 `[1]` 只会诱使她无意义地引用（并在历史上留下一堆指代）。
    形态参照既有「（他引用了你之前说的「XXX」）」那种人话，不搞花哨格式。
    """
    if not batch or len(batch) < 2:
        return ""
    lines = []
    for item in batch:
        text = (item.get("text") or "").strip()
        if not text:
            text = "（发来一张图片）" if item.get("has_image") else "（一条空消息）"
        # 单行化：批次里每条就是一条消息，不该再出现换行去骗模型
        text = text.replace("\r", " ").replace("\n", " ")
        lines.append(f"[{item.get('index')}] {text}")
    return "他这一轮连着发了这些（数字是编号，引用时用）：\n" + "\n".join(lines)


