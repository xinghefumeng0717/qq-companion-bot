def _build_face_lexicon(per_line: int = 4) -> str:
    items = [f"[{name}]＝{meaning}" for name, meaning in PROMPT_FACE_LIST]
    lines = ["、".join(items[i : i + per_line]) for i in range(0, len(items), per_line)]
    return ("\n  ".join(lines))


