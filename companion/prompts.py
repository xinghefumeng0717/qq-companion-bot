def face_prompt_block(world: Any = None) -> str:
    """表情说明块。旧卡（face_word = "QQ"、face_usage = "normal"）逐字节是原文；
    新卡不提 QQ，免得终端里聊天的角色说漏嘴；face_usage = "rare" 换低频版纪律。"""
