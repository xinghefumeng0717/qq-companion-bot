def get_mood_label(v: float, a: float) -> str:
    """根据 valence 和 arousal 判定情绪标签"""
    if v >= 4.0 and a >= 4.0:
        return "欣喜"
    if v >= 4.0 and a < 4.0:
        return "恬静"
    if v < 0.0 and a >= 4.0:
        return "焦躁"
    if v < 0.0 and a < -3.0:
        return "低落"
    if v < -4.0:
        return "忧郁"
    if v >= 3.0 and a >= -2.0:
        return "愉悦"
    return "平静"


def get_mood_description(v: float, a: float) -> str:
    """心情描述"""
    if v >= 5.0:
        desc = "心情很好，充满温暖"
    elif v >= 3.0:
        desc = "心情不错，柔和而愉悦"
    elif v >= 1.0:
        desc = "心情平静中带着淡淡的满足"
    elif v >= -1.0:
        desc = "心情平和，没有太多波澜"
    elif v >= -3.0:
        desc = "心情有些低落"
    else:
        desc = "心里有些沉重，不想说话"

    if a >= 4.0:
        desc += "，精神比较活跃"
    elif a <= -2.0:
        desc += "，整个人很安静"
    return desc


def get_trust_description(t: float) -> str:
    """信任描述"""
    if t < 3.0:
        return "心里还有些不安，不太敢完全放开"
    if t < 5.0:
        return "还有些小心翼翼，想靠近又怕受伤"
    if t < 7.0:
        return "逐渐安心了，但有些话还不太敢说"
    if t < 9.0:
        return "在你身边感到很安心"
    return "完全的信任和放松，什么都不用怕"


def get_frustration_description(frustration: float) -> str:
    """挫败/冷落驱力修饰"""
    if frustration > 6.0:
        return "。但心里有些委屈，不是生气，是不知道你有没有在意"
    if frustration > 3.0:
        return "。有点想你了，又不想说太多次"
    return ""


def get_neglect_description(hours_since_chat: float, composite_affection: float) -> str:
    """冷落描述（hours_since_chat > 12 时）"""
    if hours_since_chat > 12.0:
        if composite_affection > 60.0:
            return "；她之前没意识到，原来自己一直在等"
        hours_int = int(hours_since_chat)
        return f"；已经{hours_int}小时没有你的消息了"
    return ""


