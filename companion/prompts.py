    usage = getattr(world, "face_usage", "normal")
    base = FACE_PROMPT_BLOCK_RARE if usage == "rare" else FACE_PROMPT_BLOCK
    if word == "QQ":
        return base
    return base.replace("QQ系统表情", f"{word}系统表情").replace("都是QQ表情", f"都是{word}表情")

