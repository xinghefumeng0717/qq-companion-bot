def _build_name_index() -> Dict[str, int]:
    """名称 → face id 的反查表（canonical：优先可见的最低 id）。

    重名 8 组（450~457 是 1~8 的另一套渲染）取低位——低位那套可见可发，
    高位那套多数落在 QQ_FACE_HIDDEN 里，发出去有被静默丢段的风险。
    全部 id 都隐藏时退化为最低 id，至少让收侧/读侧有个一致的答案。
    """
    index: Dict[str, int] = {}
    for face_id in sorted(QQ_FACE_TAGS):
        name = QQ_FACE_TAGS[face_id]
        current = index.get(name)
        if current is None:
            index[name] = face_id
            continue
        cur_hidden = current in QQ_FACE_HIDDEN
        new_hidden = face_id in QQ_FACE_HIDDEN
        if cur_hidden and not new_hidden:
            index[name] = face_id          # 换成一个可见的
        elif cur_hidden == new_hidden and face_id < current:
            index[name] = face_id          # 同为可见（或同为隐藏）取低位
    return index


# 名称 → canonical face id（发侧反查用）
QQ_FACE_ID_BY_NAME: Dict[str, int] = _build_name_index()


# ==========================================
# 2. 发侧：标签名 → face id
# ==========================================


def face_id_by_name(name: str) -> Optional[int]:
    """把表情标签名反查成 face id；查不到返回 None（调用方负责按文字降级）。

    名称两端空白与大小写差异都容忍：`[face: 旺柴 ]`、`[face:DOGE]` 都能查到。
    """
    if not name:
        return None
    key = name.strip()
    if not key:
        return None
    hit = QQ_FACE_ID_BY_NAME.get(key)
    if hit is not None:
        return hit
    lowered = key.lower()
    for candidate, face_id in QQ_FACE_ID_BY_NAME.items():
        if candidate.lower() == lowered:
            return face_id
    return None


def is_sendable_face_id(face_id: Optional[int]) -> bool:
    """发侧版本闸：id 在表里、且不是被 QQ 隐藏的那批，才算"发得出"。

    供单测与部署前自查用（任务书任务4 第3条）。
    """
    if face_id is None:
        return False
    return face_id in QQ_FACE_TAGS and face_id not in QQ_FACE_HIDDEN


# ==========================================
# 3. 收侧：消息段 → 方括号文字标签
# ==========================================


def face_tag_by_id(face_id: Any) -> str:
    """face 段 → `[名称]`；id 缺失或查不到降级 `[表情]`（任务书任务1 第2条）。"""
    try:
        key = int(face_id)
    except (TypeError, ValueError):
        return UNKNOWN_FACE_TAG
    name = QQ_FACE_TAGS.get(key)
    if not name:
        return UNKNOWN_FACE_TAG
    return f"[{name}]"


def mface_tag(seg_data: Any) -> Optional[str]:
    """商城/大表情段（或被转成 image 段的大表情）→ `[summary]` / `[大表情]`。

    NapCat 收侧会把 mface 转成 image 段并带上 `summary`（表情名）与 `emoji_id`，
    所以**传进来的既可能是 mface 段的 data，也可能是 image 段的 data**，同一套逻辑通吃。
    不是大表情（普通图片没有这两个字段）返回 None，调用方按普通图片处理。
    """
    if not isinstance(seg_data, dict):
        return None
    summary = seg_data.get("summary")
    if isinstance(summary, str) and summary.strip():
        return f"[{summary.strip()}]"
    emoji_id = seg_data.get("emoji_id")
    if emoji_id not in (None, "", "0", 0):
        return UNKNOWN_MFACE_TAG
    return None


def segment_face_tag(seg: Any) -> Optional[str]:
    """OneBot 消息段 → 表情标签文本；与表情无关的段返回 None。

    收侧唯一入口：`onebot._process_incoming_message`（实时来消息）与
    `onebot._extract_message_text`（引用回查）都走它，保证两条路判定一致。
    识别三种段：
      - `face`：小黄脸，data 只有 id，名称全靠 QQ_FACE_TAGS 这张本地表
      - `mface`：商城大表情（NapCat 一般已转成 image，但仍兜住）
      - `image` + summary/emoji_id：被转换后的大表情
    """
    if not isinstance(seg, dict):
        return None
    stype = seg.get("type")
    sdata = seg.get("data") or {}
    if not isinstance(sdata, dict):
        sdata = {}
    if stype == "face":
        return face_tag_by_id(sdata.get("id"))
    if stype == "mface":
        return mface_tag(sdata) or UNKNOWN_MFACE_TAG
    if stype == "image":
        return mface_tag(sdata)
    return None
